# Simulador de meia de estudos

meta_horas = 120
horas_estudadas = 10
horas_por_dia = 2

dias_necessarios = (meta_horas - horas_estudadas) / horas_por_dia

print(f"Meta total: {meta_horas} horas")
print(f"Horas já estudadas: {horas_estudadas}")
print(f"Dias necessarios para concluir: {dias_necessarios}")